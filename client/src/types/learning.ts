import type { ApiRecord, Deck } from './base';

/** A kana sentence card. */
export type KanaCard = ApiRecord & {
  kana: string;
  romaji: string;
  script?: string;
  groupName?: string;
  mnemonic?: string;
  example?: [string, string, string];
};

/** A kanji character card. */
export type KanjiCard = ApiRecord & {
  kanji: string;
  romaji: string;
  english?: string;
  groupId?: string;
  groupName?: string;
};

/** A fetched/generated deck of study cards. */
export type CardDeck<TCard extends ApiRecord = ApiRecord> = {
  cards: TCard[];
  groups?: ApiRecord[];
  matrices?: ApiRecord[];
};

/** The concrete grammar question kinds the generator can emit. */
export type GrammarQuestionType =
  | 'multiple-choice'
  | 'fill-in-the-blank'
  | 'matching'
  | 'translation'
  | 'comprehension';

/** A single left→right pairing used by matching questions/answers. */
export type MatchingPair = { left: string; right: string };

/** The in-progress state of a matching answer (pairs built so far). */
export type MatchingAnswerState = {
  selectedLeft: string | null;
  selectedRight: string | null;
  pairs: MatchingPair[];
};

/** The union of values an answer slot can hold for grammar questions. */
export type GrammarAnswer = string | MatchingPair[] | MatchingAnswerState;

/** Answers keyed by question index. */
export type AnswerMap = Record<number, GrammarAnswer>;

/** A grammar question as generated by the grammar assessment endpoint. */
export type GrammarQuestion = ApiRecord & {
  type?: GrammarQuestionType;
  prompt?: string;
  lesson?: number;
  englishText?: string;
  correctAnswer?: string;
  correctAnswerRomaji?: string;
  choices?: string[];
  leftItems?: string[];
  rightItems?: string[];
  acceptedAnswers?: string[] | string;
  correctPairs?: MatchingPair[] | Record<string, string>;
  explanation?: string;
};

/** A generated grammar assessment (room or solo practice). */
export type GrammarAssessment = {
  type: Deck;
  maxLesson: number;
  count: number;
  questions: GrammarQuestion[];
};