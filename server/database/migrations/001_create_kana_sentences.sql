create table if not exists public.kana_sentences (
  id bigint generated by default as identity primary key,
  kana text not null,
  romaji text not null,
  english text not null,
  difficulty text not null default 'n5' check (difficulty in ('n5', 'n4', 'n3', 'n2', 'n1')),
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists kana_sentences_published_difficulty_idx
  on public.kana_sentences (is_published, difficulty);

create or replace function public.get_random_kana_sentences(
  requested_count integer default 10,
  requested_difficulty text default 'n5'
)
returns setof public.kana_sentences
language sql
stable
as $$
  select *
  from public.kana_sentences
  where is_published = true
    and difficulty = requested_difficulty
  order by random()
  limit least(greatest(requested_count, 1), 25);
$$;
